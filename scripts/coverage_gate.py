#!/usr/bin/env python3
"""Coverage gate: >= 80% on `domain` and `modules` (PRD section 14).

Reads the coverage.xml produced by `make test` and reports per-package numbers, so a gate
failure names the package that needs tests rather than a single global percentage.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent / "backend"
REPORT = BACKEND / "coverage.xml"
THRESHOLD = 80.0
GATED_PREFIXES = ("tazama/domain", "tazama/modules", "tazama/core")


def main() -> int:
    if not REPORT.exists():
        print(f"coverage report not found at {REPORT}; run: make test")  # noqa: T201
        return 1
    raw = REPORT.read_text(encoding="utf-8", errors="ignore")
    # The file is generated by our own test run, but parse defensively anyway: refuse any
    # doctype or entity declaration rather than hand it to expat (XXE / entity expansion).
    if "<!DOCTYPE" in raw or "<!ENTITY" in raw:
        print("coverage.xml contains a doctype/entity declaration; refusing to parse it")  # noqa: T201
        return 1
    root = ET.fromstring(raw)  # noqa: S314 - doctype/entity rejected above

    totals: dict[str, list[int]] = {prefix: [0, 0] for prefix in GATED_PREFIXES}
    overall = [0, 0]
    for cls in root.iter("class"):
        # coverage.py records paths relative to its source root, which may or may not
        # include the `src/` prefix depending on how pytest was invoked.
        filename = (cls.get("filename") or "").replace("\\", "/").removeprefix("src/")
        lines = [ln for ln in cls.iter("line") if ln.get("hits") is not None]
        covered = sum(1 for ln in lines if ln.get("hits") != "0")
        total = len(lines)
        overall[0] += covered
        overall[1] += total
        for prefix in GATED_PREFIXES:
            if filename.startswith(prefix):
                totals[prefix][0] += covered
                totals[prefix][1] += total

    def pct(covered: int, total: int) -> float:
        return 100.0 if total == 0 else round(100.0 * covered / total, 2)

    failures: list[str] = []
    print("coverage by gated package:")  # noqa: T201
    for prefix, (covered, total) in totals.items():
        value = pct(covered, total)
        status = "ok" if value >= THRESHOLD or total == 0 else "FAIL"
        note = " (no measurable lines yet)" if total == 0 else ""
        print(f"  {prefix:<18} {value:6.2f}%  [{status}]{note}")  # noqa: T201
        if total and value < THRESHOLD:
            failures.append(f"{prefix} at {value:.2f}% (needs {THRESHOLD:.0f}%)")
    print(f"  {'overall':<18} {pct(*overall):6.2f}%")  # noqa: T201

    if failures:
        print("\ncoverage gate FAILED:")  # noqa: T201
        for failure in failures:
            print(f"  {failure}")  # noqa: T201
        return 1
    print("\ncoverage gate: ok")  # noqa: T201
    return 0


if __name__ == "__main__":
    sys.exit(main())
