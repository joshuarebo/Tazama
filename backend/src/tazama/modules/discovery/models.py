"""DTOs for the discovery module: catalog, profile, join coverage, query results.

These are plain data: the service builds them, the API serialises them, and the catalog
renders itself to Markdown for `docs/data-catalog.md`. Nothing here touches a database.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Literal

#: Tables big enough that an unbounded scan is a performance problem worth warning about.
LARGE_TABLES: frozenset[str] = frozenset(
    {"kpi_cell", "complaint", "care_call", "audit_log", "subscriber", "alarm"},
)


@dataclass(frozen=True, slots=True)
class ColumnProfile:
    """What the profiler knows about one column (PRD section 7)."""

    name: str
    type: str
    nullable: bool
    primary_key: bool = False
    indexed: bool = False
    is_pii: bool = False
    null_count: int | None = None
    distinct_count: int | None = None
    min_value: str | None = None
    max_value: str | None = None
    sample: tuple[str, ...] = ()

    def null_pct(self, row_count: int) -> float | None:
        if self.null_count is None or row_count <= 0:
            return None
        return round(100.0 * self.null_count / row_count, 2)

    def cardinality_ratio(self, row_count: int) -> float | None:
        if self.distinct_count is None or row_count <= 0:
            return None
        return round(self.distinct_count / row_count, 4)


@dataclass(frozen=True, slots=True)
class TableProfile:
    name: str
    row_count: int
    columns: tuple[ColumnProfile, ...]
    freshness: datetime | None = None
    freshness_column: str | None = None
    is_large: bool = False
    app_owned: bool = True
    mapped_source: str | None = None
    notes: tuple[str, ...] = ()

    @property
    def pii_columns(self) -> tuple[str, ...]:
        return tuple(c.name for c in self.columns if c.is_pii)

    def column(self, name: str) -> ColumnProfile | None:
        return next((c for c in self.columns if c.name == name), None)


@dataclass(frozen=True, slots=True)
class CoverageRow:
    """One join-coverage measurement: the day-one metric of the hardest problem."""

    question: str
    resolved: int
    total: int
    detail: str = ""

    @property
    def pct(self) -> float:
        return 0.0 if not self.total else round(100.0 * self.resolved / self.total, 2)


@dataclass(frozen=True, slots=True)
class JoinCoverage:
    """Complaint → cell → site → incident resolvability, plus time alignment."""

    measured_at: datetime
    window_start: datetime | None
    window_end: datetime | None
    rows: tuple[CoverageRow, ...]
    time_alignment: tuple[CoverageRow, ...] = ()
    warnings: tuple[str, ...] = ()

    def row(self, question: str) -> CoverageRow | None:
        return next((r for r in self.rows if r.question == question), None)

    @property
    def complaint_to_cell_pct(self) -> float:
        row = self.row("complaint -> cell")
        return row.pct if row else 0.0

    def render(self) -> str:
        lines = [
            f"join coverage measured at {self.measured_at.isoformat()}",
            "",
            f"  {'question':<28} {'resolved':>10} {'total':>10} {'pct':>8}",
            f"  {'-' * 28} {'-' * 10} {'-' * 10} {'-' * 8}",
        ]
        for row in self.rows:
            lines.append(
                f"  {row.question:<28} {row.resolved:>10,} {row.total:>10,} {row.pct:>7.2f}%",
            )
        if self.time_alignment:
            lines += ["", "  time alignment:"]
            lines += [
                f"    {row.question:<26} {row.pct:>7.2f}%  {row.detail}"
                for row in self.time_alignment
            ]
        if self.warnings:
            lines += ["", "  warnings:"] + [f"    - {w}" for w in self.warnings]
        return "\n".join(lines)


@dataclass(frozen=True, slots=True)
class CatalogSnapshot:
    generated_at: datetime
    app_mode: str
    db_backend: str
    tables: tuple[TableProfile, ...]
    mapping_summary: str = ""
    coverage: JoinCoverage | None = None
    seed_note: str = ""

    @property
    def total_rows(self) -> int:
        return sum(t.row_count for t in self.tables)

    def table(self, name: str) -> TableProfile | None:
        return next((t for t in self.tables if t.name == name), None)

    def to_markdown(self) -> str:
        """Render `docs/data-catalog.md`.

        The caveats at the top are deliberate: a catalog that looks authoritative about
        synthetic data is how modelled thresholds end up quoted as facts.
        """
        lines: list[str] = [
            "# Data catalog",
            "",
            f"Generated: {self.generated_at.isoformat()} · mode: **{self.app_mode}** · "
            f"backend: **{self.db_backend}**",
            "",
            "> Generated by `make catalog` — do not edit by hand.",
            "",
            "## Caveats",
            "",
            "* **Synthetic data.** Every row is generated by `make seed`. Volumes, "
            "distributions and KPI values are modelled, not measured.",
            "* **KPI names and thresholds are UNVERIFIED.** They follow standard RAN "
            "practice (accessibility via RRC/E-RAB setup success, retainability via drop "
            "rate, integrity via throughput and latency, utilisation via PRB) but each "
            "operator defines its own counters. Reconcile with the real counter "
            "definitions before any live use.",
            "* **No raw subscriber identifiers exist in this schema.** `subscriber.id` is "
            "an HMAC pseudonym; columns marked PII are masked by default in the explorer "
            "and in exports.",
            "",
        ]
        if self.mapping_summary:
            lines += ["## Source mappings", "", self.mapping_summary, ""]
        if self.seed_note:
            lines += ["## Seed provenance", "", self.seed_note, ""]
        if self.coverage is not None:
            lines += [
                "## Join coverage",
                "",
                "The complaint → network-element join is the hardest problem in this "
                "product, so it is measured on every catalog run.",
                "",
                "| Question | Resolved | Total | Coverage |",
                "| --- | ---: | ---: | ---: |",
            ]
            lines += [
                f"| {row.question} | {row.resolved:,} | {row.total:,} | {row.pct:.2f}% |"
                for row in self.coverage.rows
            ]
            lines.append("")
            if self.coverage.time_alignment:
                lines += ["### Time alignment", ""]
                lines += [
                    f"* {row.question}: {row.pct:.2f}% — {row.detail}"
                    for row in self.coverage.time_alignment
                ]
                lines.append("")

        lines += [
            "## Tables",
            "",
            "| Table | Rows | Columns | PII columns | Freshness | Source |",
            "| --- | ---: | ---: | --- | --- | --- |",
        ]
        for table in self.tables:
            fresh = table.freshness.isoformat() if table.freshness else "—"
            pii = ", ".join(table.pii_columns) or "—"
            source = table.mapped_source or ("app-owned" if table.app_owned else "—")
            lines.append(
                f"| `{table.name}` | {table.row_count:,} | {len(table.columns)} | "
                f"{pii} | {fresh} | {source} |",
            )
        lines.append("")

        for table in self.tables:
            lines += [
                f"### `{table.name}`",
                "",
                f"Rows: **{table.row_count:,}**"
                + (
                    f" · freshness column: `{table.freshness_column}`"
                    if table.freshness_column
                    else ""
                )
                + (" · large table (queries must be time-bounded)" if table.is_large else ""),
                "",
                "| Column | Type | Null | Null % | Distinct | Min | Max | Flags |",
                "| --- | --- | --- | ---: | ---: | --- | --- | --- |",
            ]
            for column in table.columns:
                null_pct = column.null_pct(table.row_count)
                flags = (
                    ", ".join(
                        flag
                        for flag, on in (
                            ("pk", column.primary_key),
                            ("idx", column.indexed),
                            ("pii", column.is_pii),
                        )
                        if on
                    )
                    or "—"
                )
                lines.append(
                    f"| `{column.name}` | {column.type} | {'yes' if column.nullable else 'no'} | "
                    f"{'—' if null_pct is None else f'{null_pct:.2f}'} | "
                    f"{'—' if column.distinct_count is None else f'{column.distinct_count:,}'} | "
                    f"{column.min_value or '—'} | {column.max_value or '—'} | {flags} |",
                )
            if table.notes:
                lines += [""] + [f"* {note}" for note in table.notes]
            lines.append("")
        return "\n".join(lines)


