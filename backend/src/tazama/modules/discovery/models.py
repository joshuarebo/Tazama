ProfileDepth = Literal["shallow", "full"]


@dataclass(frozen=True, slots=True)
class ProfileRequest:
    """`shallow` reads counts and index metadata only; `full` adds per-column statistics,
    which is the expensive part on large tables."""

    tables: tuple[str, ...] = ()
    depth: ProfileDepth = "full"
    sample_rows: int = 3
    exclude: frozenset[str] = field(default_factory=frozenset)
