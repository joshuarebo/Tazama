@dataclass(frozen=True, slots=True)
class QueryColumn:
    name: str
    masked: bool = False


@dataclass(frozen=True, slots=True)
class QueryResult:
    """Result of a Data Explorer query, already capped and masked."""

    columns: tuple[QueryColumn, ...]
    rows: tuple[tuple[Any, ...], ...]
    row_count: int
    truncated: bool
    duration_ms: float
    executed_sql: str
    warnings: tuple[str, ...] = ()

    @property
    def column_names(self) -> tuple[str, ...]:
        return tuple(c.name for c in self.columns)

    def to_csv(self) -> str:
        """CSV of the already-masked result. Values are quoted defensively.

        A leading `=`, `+`, `-` or `@` is prefixed with a quote so a spreadsheet treats
        the cell as text rather than a formula (CSV injection).
        """
        import csv
        import io

        buffer = io.StringIO()
        writer = csv.writer(buffer, lineterminator="\n")
        writer.writerow(self.column_names)
        for row in self.rows:
            writer.writerow([_csv_safe(value) for value in row])
        return buffer.getvalue()


def _csv_safe(value: Any) -> str:
    if value is None:
        return ""
    text = str(value)
    if text[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + text
    return text


